-- 1. TABEL ALAT
CREATE TABLE IF NOT EXISTS public.alat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL UNIQUE,
    kategori TEXT NOT NULL,
    stok INTEGER NOT NULL DEFAULT 0,
    keterangan TEXT DEFAULT '',
    aktif BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT alat_nama_check
        CHECK (char_length(nama) BETWEEN 3 AND 40),

    CONSTRAINT alat_kategori_check
        CHECK (kategori IN (
            'kamera',
            'pencahayaan',
            'audio',
            'tablet',
            'aksesori'
        )),

    CONSTRAINT alat_stok_check
        CHECK (stok BETWEEN 0 AND 50)
);


-- 2. TABEL PEMINJAMAN ALAT
CREATE TABLE IF NOT EXISTS public.peminjaman_alat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    alat_id BIGINT NOT NULL
        REFERENCES public.alat(id),

    peminjam TEXT NOT NULL,
    kelas TEXT NOT NULL,
    keperluan TEXT NOT NULL,
    jumlah INTEGER NOT NULL,

    tgl_pinjam DATE NOT NULL,
    tgl_kembali DATE NOT NULL,

    status TEXT NOT NULL DEFAULT 'menunggu',
    alasan_tolak TEXT DEFAULT '',
    kondisi_kembali TEXT DEFAULT '',
    tgl_dikembalikan DATE DEFAULT NULL,

    dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT peminjam_check
        CHECK (char_length(peminjam) BETWEEN 3 AND 40),

    CONSTRAINT kelas_check
        CHECK (char_length(kelas) BETWEEN 3 AND 20),

    CONSTRAINT keperluan_check
        CHECK (char_length(keperluan) BETWEEN 5 AND 120),

    CONSTRAINT jumlah_check
        CHECK (jumlah BETWEEN 1 AND 5),

    CONSTRAINT status_check
        CHECK (status IN (
            'menunggu',
            'dipinjam',
            'dikembalikan',
            'ditolak'
        )),

    CONSTRAINT kondisi_check
        CHECK (
            kondisi_kembali = ''
            OR kondisi_kembali IN (
                'baik',
                'rusak ringan',
                'rusak berat'
            )
        ),

    CONSTRAINT tanggal_check
        CHECK (tgl_kembali >= tgl_pinjam)
);


-- 3. MENGAKTIFKAN RLS
ALTER TABLE public.alat ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.peminjaman_alat ENABLE ROW LEVEL SECURITY;


-- 4. HAK AKSES PENGUNJUNG
-- Pengunjung hanya dapat membaca alat.

GRANT SELECT ON public.alat TO anon;
GRANT SELECT ON public.alat TO authenticated;

REVOKE ALL ON public.peminjaman_alat FROM anon;
REVOKE ALL ON public.peminjaman_alat FROM authenticated;


-- 5. HAK AKSES SERVER ADMIN
-- Server menggunakan secret/service role key.

GRANT ALL ON public.alat TO service_role;
GRANT ALL ON public.peminjaman_alat TO service_role;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public
TO service_role;


-- 6. POLICY TABEL ALAT
DROP POLICY IF EXISTS "alat_baca_pengunjung"
ON public.alat;

CREATE POLICY "alat_baca_pengunjung"
ON public.alat
FOR SELECT
TO anon, authenticated
USING (true);


